// Adds an entry to the bot's update log.
//   node PinguinoChat\add-update.mjs "Short title" "What changed, in a sentence or two" [who]
// Writes PinguinoChat\updates.json (the chat bot reads it, so it knows when it changed) and regenerates PinguinoChat\UPDATES.md (readable by hand).
// Anyone who changes the bot (you, Claude sessions, scripts) should run this after the change, with the real time of the change.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const jsonPath = path.join(dir, 'updates.json');
const [title, details = '', by = 'claude'] = process.argv.slice(2);
if (!title) {
  console.error('Usage: node add-update.mjs "Title" "Details" [who]');
  process.exit(1);
}

let list = [];
try { list = JSON.parse(fs.readFileSync(jsonPath, 'utf8')); } catch { list = []; }

// local time with the UTC offset, e.g. 2026-10-19T03:10:00-05:00
const d = new Date();
const pad = (n) => String(n).padStart(2, '0');
const off = -d.getTimezoneOffset();
const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}` +
  `${off >= 0 ? '+' : '-'}${pad(Math.floor(Math.abs(off) / 60))}:${pad(Math.abs(off) % 60)}`;

list.push({ At: stamp, By: by, Title: title, Details: details });
list.sort((a, b) => String(a.At).localeCompare(String(b.At)));
fs.writeFileSync(jsonPath, JSON.stringify(list, null, 2) + '\n', 'utf8');

const md = ['# PinguinoBot updates', '', 'Newest first. Times are the local time of the PC (Central). The bot reads `updates.json`; this file is generated by `add-update.mjs`.', ''];
for (const e of [...list].reverse()) {
  md.push(`## ${String(e.At).replace('T', ' ').slice(0, 16)}  ${e.Title}`, `*by ${e.By}*`, '', e.Details || '', '');
}
fs.writeFileSync(path.join(dir, 'UPDATES.md'), md.join('\n'), 'utf8');
console.log(`Added: ${stamp} ${title}`);
