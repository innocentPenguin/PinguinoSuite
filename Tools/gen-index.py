"""Writes the line-numbered 'PinguinoB0t bots' block in Docs/INDEX.md (only between its own markers; other sessions' headings stay).
Usage: python Tools/gen-index.py   (re-run after big edits; line numbers go stale otherwise)"""
import os, re, sys
suite = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN, END = '<!-- B0T-INDEX-BEGIN -->', '<!-- B0T-INDEX-END -->'
bots = [('PinguinoB0t/PinguinoBotCore.cs', 'PinguinoB0t core: queue, teams, KOTH, strikes, OBS, site bridge (Streamer.bot action)'),
        ('PinguinoB0t/PinguinoBotFirsts.cs', 'First-5 chat game'),
        ('PinguinoChat/PinguinoChat.cs', 'ChattyPinguino: AI chat, !8ball, opinions, memory'),
        ('HelperPinguino/PinguinoHelper.cs', 'HelperPinguino: short help answers, site links, review log'),
        ('Shared/PinguinoRouter.cs', 'Router: decides which bot answers; also PgSay duplicate guard')]
host = ['HostFeatureCommands', 'HostBoards', 'HostLatest', 'HostEmotes', 'HostTimers', 'HostStreamTimers', 'HostReminders', 'HostHelperReview', 'HostEconomy']
sec = re.compile(r'^\s*//\s*(?:──+|═+)\s*(.+?)\s*(?:──+|═+)?\s*$')
shared_b, shared_e = '// <<PINGUINO-SHARED-BEGIN>>', '// <<PINGUINO-SHARED-END>>'
out = [BEGIN, '', '## PinguinoB0t bots (generated by Tools/gen-index.py)', '']
def rd(p): return open(os.path.join(suite, p), encoding='utf-8-sig', errors='replace').read().splitlines()
for p, what in bots:
    if not os.path.exists(os.path.join(suite, p)): continue
    L = rd(p); out += ['### ' + p + ' (%d lines) - %s' % (len(L), what), '']
    inshared = False; rows = []
    for i, l in enumerate(L, 1):
        if shared_b in l: inshared = True; rows.append('| %d | (shared block start: Pg* helpers, PgSay + duplicate guard, router helpers - identical in every bot, edit Shared/PinguinoBots.cs.txt) |' % i); continue
        if shared_e in l: inshared = False; rows.append('| %d | (shared block end) |' % i); continue
        if inshared: continue
        m = sec.match(l)
        if m and len(m.group(1)) > 3: rows.append('| %d | %s |' % (i, m.group(1).strip()[:110]))
    out += ['| line | section |', '|---|---|'] + rows + ['']
    meth = re.compile(r'^    (?:public |private |internal |static |async )*[\w<>\[\],\.]+ ((?:Handle|Run|Execute|Dispatch|Publish|Build|Save|Load|Post|Say|Apply|Record|Start|Pull|Switch|Report|Try|Do|Maybe|Is|Parse|Show|Send)\w*)\(')
    ins = False; ms = []
    for i, l in enumerate(L, 1):
        if shared_b in l: ins = True
        if shared_e in l: ins = False; continue
        if ins: continue
        m = meth.match(l)
        if m: ms.append('%s:%d' % (m.group(1), i))
    if ms: out += ['Methods (name:line, outside the shared block): ' + ', '.join(ms), '']
out += ['### Host modules owned by 02 (PinguinoHost/)', '', '| file | lines | what |', '|---|---|---|']
for h in host:
    p = 'PinguinoHost/%s.cs' % h
    if not os.path.exists(os.path.join(suite, p)): continue
    L = rd(p); what = ''
    for l in L:
        m = re.search(r'///\s*<summary>(.*)', l)
        if m: what = re.sub(r'</?summary>', '', m.group(1)).strip()[:150]; break
    out.append('| %s | %d | %s |' % (p, len(L), what))
out += ['', END, '']
f = os.path.join(suite, 'Docs', 'INDEX.md'); block = '\n'.join(out)
s = open(f, encoding='utf-8').read() if os.path.exists(f) else '# Index of the suite\n\nEach session keeps its own heading/block; generators only touch their own markers.\n\n'
if BEGIN in s and END in s: s = s[:s.index(BEGIN)] + block + s[s.index(END) + len(END):].lstrip('\n')
else: s = s.rstrip('\n') + '\n\n' + block
open(f, 'w', encoding='utf-8', newline='\n').write(s); print('wrote', f, len(out), 'lines')
