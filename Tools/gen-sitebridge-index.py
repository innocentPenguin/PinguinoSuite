"""Writes the line-numbered 'Site bridges' block in Docs/INDEX.md between its own markers (SITEBRIDGE-INDEX). Re-run after edits to HostSiteBridge.cs."""
import os, re
suite = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B, E = '<!-- SITEBRIDGE-INDEX-BEGIN -->', '<!-- SITEBRIDGE-INDEX-END -->'
src = os.path.join(suite, 'PinguinoHost', 'HostSiteBridge.cs')
L = open(src, encoding='utf-8-sig').read().splitlines()
cls = re.compile(r'^    public static class (\w+)'); fn = re.compile(r'^        (?:public |internal |private )?static [\w<>\[\],\.]+ (\w+)\(')
rows = []; cur = None
for i, l in enumerate(L, 1):
    m = cls.match(l)
    if m: cur = [m.group(1), i, []]; rows.append(cur); continue
    m = fn.match(l)
    if m and cur: cur[2].append('%s:%d' % (m.group(1), i))
out = [B, '', '## Site bridges (Host <-> innocentpenguin.com; generated by Tools/gen-sitebridge-index.py)', '',
       'Code: `PinguinoHost/HostSiteBridge.cs` (%d lines). Contract: [SHOP_BRIDGE.md](SHOP_BRIDGE.md); host side: [SITE_BRIDGES.md](SITE_BRIDGES.md). Test: `python -I Tools/test-host-sitebridge.py <host dll>`. Status: `GET /api/sitebridge`. State: `Data/runtime/site_teach.json`, `site_shop.json`, `chatty_unlock.json`, optional `site_shop_settings.json`. Switches: settings `SiteTeachBridge`, `SiteShop`.' % len(L), '',
       '| class | line | functions (name:line) |', '|---|---|---|']
for n, i, f in rows: out.append('| %s | %d | %s |' % (n, i, ', '.join(f)))
out += ['', E]
p = os.path.join(suite, 'Docs', 'INDEX.md'); t = open(p, encoding='utf-8').read(); blk = '\n'.join(out)
if B in t: t = re.sub(re.escape(B) + '.*?' + re.escape(E), lambda m: blk, t, flags=re.S)
else: t = t.rstrip('\n') + '\n\n' + blk + '\n'
open(p, 'w', encoding='utf-8', newline='').write(t)
print('ok', len(rows), 'classes')
