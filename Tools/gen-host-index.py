"""Writes the PinguinoHost section of Docs/INDEX.md (between the HOST-INDEX markers): one block per source file with its summary line, classes and methods with line numbers,
plus the data files, tools, tests and the HTTP routes. Run: python Tools/gen-host-index.py"""
import glob, os, re
here = os.path.dirname(os.path.abspath(__file__)); suite = os.path.dirname(here)
B, E = '<!-- HOST-INDEX-BEGIN -->', '<!-- HOST-INDEX-END -->'
out = ['## PinguinoHost (generated by Tools/gen-host-index.py; owner: 02)', '',
       'Data files: Data\\boards\\{aliases,banned_accounts,totals}.json, Data\\config\\{control,raid_list}.json, Data\\runtime\\{control_log.jsonl,mod_audit.log,unping.json,trusted.json,followed.json}, Data\\rank\\rank.json, Data\\namehistory\\*.json, Data\\chat_logs\\{live,sidecar,hidden_sources.json}.',
       'Tools: Tools\\test-host-*.py (Host tests, run with the built dll), Tools\\build-namehistory.py, Tools\\gen-index.py, Tools\\gen-host-index.py. Docs: Docs\\HOST.md, Docs\\NAMEHISTORY.md, Docs\\ROCKETRANKBOT_AUDIT.md.', '']
routes = {}
for f in sorted(glob.glob(os.path.join(suite, 'PinguinoHost', '*.cs'))):
    name = os.path.basename(f); lines = open(f, encoding='utf-8-sig', errors='replace').read().split('\n')
    summ = ''
    for l in lines[:60]:
        m = re.search(r'<summary>(.*?)(</summary>|$)', l)
        if m and m.group(1).strip(): summ = re.sub(r'<[^>]+>', '', m.group(1)).strip()[:160]; break
    cls = [(i + 1, m.group(1)) for i, l in enumerate(lines) for m in [re.search(r'\b(?:static |public |internal )*(?:partial )?class (\w+)', l)] if m]
    meths = []
    for i, l in enumerate(lines):
        m = re.match(r'\s{8}(?:public |internal |private )?(?:static )(?:[\w<>\[\],. ?]+?) (\w+)\(', l)
        if m and m.group(1) not in ('if', 'for', 'foreach', 'while', 'switch', 'using', 'lock') and not l.strip().startswith(('return', 'new ')): meths.append('%s:%d' % (m.group(1), i + 1))
        for r in re.findall(r'p == "(/[a-z0-9/_-]+)"', l): routes.setdefault(r, name)
    out.append('### PinguinoHost/%s (%d lines)%s' % (name, len(lines), ' - ' + summ if summ else ''))
    if cls: out.append('Classes: ' + ', '.join('%s:%d' % (n, ln) for ln, n in cls))
    if meths: out.append('Methods: ' + ', '.join(meths[:40]) + (' ...' if len(meths) > 40 else ''))
    out.append('')
out.append('### HTTP routes (127.0.0.1:8770; POST needs same-origin or a token; module routes always need the module token)')
out.append(', '.join('%s (%s)' % (r, f) for r, f in sorted(routes.items())))
out.append('')
block = B + '\n\n' + '\n'.join(out) + '\n' + E
p = os.path.join(suite, 'Docs', 'INDEX.md'); t = open(p, encoding='utf-8').read()
if B in t: t = t[:t.index(B)] + block + t[t.index(E) + len(E):]
else: t = t.rstrip('\n') + '\n\n' + block + '\n'
open(p, 'w', encoding='utf-8', newline='').write(t)
print('wrote', len(out), 'lines')
